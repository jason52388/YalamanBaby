// Normalize the lookup table (drop dedup suffixes like "_unisex" used to keep
// the literal map unique).
const meanings = {};
for (const [k, v] of Object.entries(RAW)) {
  const cleanKey = k.replace(/_.*$/, '');
  if (!meanings[cleanKey]) meanings[cleanKey] = { origin: v[0], meaning: v[1] };
}

/** Look up a name (case-insensitive). Returns { origin, meaning } or null. */
export function lookupMeaning(name) {
  if (!name) return null;
  const key = name.trim().toLowerCase();
  return meanings[key] || null;
}
